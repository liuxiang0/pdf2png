/**
 * 生成测试用 PDF（纯文本内容，A4/Letter 尺寸），避免把二进制样本提交进仓库。
 */
import fs from 'node:fs';
import path from 'node:path';

/**
 * @param {string} target 输出路径
 * @param {{pages?: number, width?: number, height?: number, label?: string}} [options]
 * @returns {string} target 的绝对路径
 */
export function makePdf(target, options = {}) {
  const pages = options.pages ?? 3;
  const width = options.width ?? 612;
  const height = options.height ?? 792;
  const label = options.label ?? 'Sample PDF';

  const objects = [];
  const offsets = [];
  let offset = 0;
  const parts = [];

  const push = (text) => {
    parts.push(text);
    offset += Buffer.byteLength(text, 'latin1');
  };
  const addObject = (number, content) => {
    offsets[number] = offset;
    push(`${number} 0 obj\n${content}\nendobj\n`);
  };

  push('%PDF-1.4\n');

  const pageNumbers = [];
  for (let i = 0; i < pages; i += 1) pageNumbers.push(3 + i);
  const fontNumber = 3 + pages;
  const firstContent = fontNumber + 1;

  addObject(1, '<< /Type /Catalog /Pages 2 0 R >>');
  addObject(
    2,
    `<< /Type /Pages /Kids [${pageNumbers.map((n) => `${n} 0 R`).join(' ')}] /Count ${pages} >>`,
  );

  for (let i = 0; i < pages; i += 1) {
    addObject(
      pageNumbers[i],
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${width} ${height}] `
      + `/Resources << /Font << /F1 ${fontNumber} 0 R >> >> `
      + `/Contents ${firstContent + i} 0 R >>`,
    );
  }

  addObject(fontNumber, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');

  for (let i = 0; i < pages; i += 1) {
    const text = [
      '0.15 0.36 0.86 rg',
      `${width * 0.08} ${height - 90} ${width * 0.84} 4 re f`,
      '0 0 0 rg',
      'BT',
      '/F1 28 Tf',
      `${width * 0.08} ${height - 150} Td`,
      `(${label} - Page ${i + 1}/${pages}) Tj`,
      'ET',
      'BT',
      '/F1 14 Tf',
      `${width * 0.08} ${height - 190} Td`,
      `(Generated by test/make-fixture.mjs) Tj`,
      'ET',
      '0.6 0.6 0.6 RG',
      '1 w',
      `${width * 0.08} ${height * 0.3} m ${width * 0.92} ${height * 0.3} l S`,
      '',
    ].join('\n');
    addObject(
      firstContent + i,
      `<< /Length ${Buffer.byteLength(text, 'latin1')} >>\nstream\n${text}\nendstream`,
    );
  }

  const maxObject = firstContent + pages - 1;
  const xrefOffset = offset;
  const xrefLines = ['xref', `0 ${maxObject + 1}`, '0000000000 65535 f '];
  for (let i = 1; i <= maxObject; i += 1) {
    xrefLines.push(`${String(offsets[i]).padStart(10, '0')} 00000 n `);
  }
  xrefLines.push('trailer', `<< /Size ${maxObject + 1} /Root 1 0 R >>`, 'startxref', String(xrefOffset), '%%EOF', '');
  push(xrefLines.join('\n'));

  const abs = path.resolve(target);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, Buffer.from(parts.join(''), 'latin1'));
  return abs;
}

/** 生成一个不是 PDF 的文件，用来测试失败路径。 */
export function makeBrokenPdf(target) {
  const abs = path.resolve(target);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, 'this is not a PDF\n');
  return abs;
}
